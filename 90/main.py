# 1. 3 ფილმისგან შემდგარი სია
movies = ["Inception", "Interstellar", "The Dark Knight"]

# 2. ყველა ფილმის დაბეჭდვა for ციკლის გამოყენებით
print("არსებული ფილმების სია:")
for movie in movies:
    print(f"- {movie}")

print()  # ცარიელი სტრიქონი დაშორებისთვის

# 3. მომხმარებლისგან ახალი ფილმის სახელის მიღება და სიაში დამატება (.append() მეთოდით)
new_movie = input("შეიყვანეთ ახალი ფილმის სახელი: ")
movies.append(new_movie)

print(f"ახალი სია: {movies}\n")

# 4. მომხმარებლისგან ინდექსის მიღება და ამ ინდექსზე არსებული ფილმის დაბეჭდვა
index = int(input(f"შეიყვანეთ ინდექსი (0-დან {len(movies) - 1}-მდე): "))

# ამოწმებს, შეყვანილი ინდექსი არის თუ არა სიის ფარგლებში
if 0 <= index < len(movies):
    print(f"არჩეულ ინდექსზე ({index}) არსებული ფილმია: {movies[index]}")
else:
    print("ასეთი ინდექსი სიაში არ არსებობს!")




